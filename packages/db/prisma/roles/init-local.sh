#!/bin/sh
set -eu

: "${FLOWPILOT_APP_PASSWORD:?FLOWPILOT_APP_PASSWORD must be set}"

psql \
  --set=ON_ERROR_STOP=1 \
  --set=app_password="$FLOWPILOT_APP_PASSWORD" \
  --set=app_database="$POSTGRES_DB" \
  --username "$POSTGRES_USER" \
  --dbname "$POSTGRES_DB" <<'SQL'
CREATE ROLE flowpilot_app
  LOGIN PASSWORD :'app_password'
  NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
GRANT CONNECT ON DATABASE :"app_database" TO flowpilot_app;
GRANT USAGE ON SCHEMA public TO flowpilot_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO flowpilot_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO flowpilot_app;
SQL
